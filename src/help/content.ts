/** 記録を探す */
export function findArticle(id: string): { chapter: Chapter; article: Article; index: number } | null {
  for (const chapter of CHAPTERS) {
    const index = chapter.articles.findIndex((a) => a.id === id);
    if (index >= 0) return { chapter, article: chapter.articles[index], index };
  }
  return null;
}

/** 記事の中の文（探すとき用） */
export function articleText(a: Article): string {
  return [
    a.title,
    ...a.blocks.flatMap((b) =>
      'p' in b ? [b.p] : 'steps' in b ? b.steps : 'tip' in b ? [b.tip] : 'img' in b ? [...(b.marks ?? []), b.cap ?? ''] : [],
    ),
  ].join('\n');
}
